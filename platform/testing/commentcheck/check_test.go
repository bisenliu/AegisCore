package commentcheck

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestCheckRootReportsMissingChineseComments(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "pkg", "missing.go"), `package pkg

func hidden() {}

func Exported() {}

type ExportedType struct{}

const (
	// 分组说明。
	Grouped = "grouped"
)
`)
	writeFile(t, filepath.Join(root, "pkg", "commented.go"), `package pkg

// ready 返回准备完成状态。
func ready() bool { return true }

// ReadyType 表示已文档化的导出类型。
type ReadyType struct{}
`)
	writeFile(t, filepath.Join(root, "pkg", "generated.go"), `// Code generated by test; DO NOT EDIT.
package pkg

func generated() {}
`)
	writeFile(t, filepath.Join(root, "pkg", "skip_test.go"), `package pkg

func TestSkipped(t *testing.T) {}
`)
	writeFile(t, filepath.Join(root, "service", "internal", "persistence", "ent", "client.go"), `package ent

func GeneratedClient() {}
`)
	writeFile(t, filepath.Join(root, "service", "internal", "persistence", "ent", "schema", "user.go"), `package schema

func schemaHelper() {}
`)

	issues, err := CheckRoot(root)
	if err != nil {
		t.Fatalf("CheckRoot() error = %v", err)
	}
	joined := formatIssues(issues)
	for _, want := range []string{"hidden", "Exported", "ExportedType", "schemaHelper"} {
		if !strings.Contains(joined, want) {
			t.Fatalf("issues = %s, want %s", joined, want)
		}
	}
	for _, forbidden := range []string{"ready", "generated", "TestSkipped", "GeneratedClient", "Grouped"} {
		if strings.Contains(joined, forbidden) {
			t.Fatalf("issues = %s, unexpectedly contains %s", joined, forbidden)
		}
	}
}

func TestCheckRootRejectsMissingDirectory(t *testing.T) {
	if _, err := CheckRoot(filepath.Join(t.TempDir(), "missing")); err == nil {
		t.Fatal("CheckRoot() error = nil, want missing directory")
	}
}

func writeFile(t *testing.T, path string, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("MkdirAll() error = %v", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("WriteFile() error = %v", err)
	}
}

func formatIssues(issues []Issue) string {
	var builder strings.Builder
	for _, item := range issues {
		builder.WriteString(item.Name)
		builder.WriteByte('\n')
	}
	return builder.String()
}
